// scripts/gen-docs.js
//
// Writes the figures in README.md and DESIGN.md that would otherwise go stale by hand:
// gzipped sizes, the current release and the pre-commit `rev:`. Part of `npm run gen`.
//
//   node scripts/gen-docs.js          write the files
//   node scripts/gen-docs.js --check  exit 1 if any file is out of date (used by `npm run ci`)
//
// Markers, invisible when the Markdown is rendered:
//   <!-- gen:size:NAME -->2.0 KiB<!-- /gen -->     gzipped size of a probe, in KiB
//   <!-- gen:bytes:NAME -->2074<!-- /gen -->       the same in bytes
//   <!-- gen:release -->1.3.8 (2026-11-02)<!-- /gen -->
//   <!-- gen:budget:NAME -->3 KiB<!-- /gen -->     the size budget of a probe, in KiB
//   <!-- gen:count:viramas -->69<!-- /gen -->      code points in src/virama.generated.js
//   <!-- gen:sizes:start -->...<!-- gen:sizes:end -->  the table of every probe
// NAME is a probe in scripts/check-size.js, or `browser` for dist/text-sanctifier.min.js.
// In README.md, `rev: vX.Y.Z  # a release tag` follows package.json, and the bundle-size
// badge follows the browser budget.

import { resolve } from 'path';
import { fileURLToPath } from 'url';
import { PROBES, measure } from './check-size.js';
import { GZIP_BUDGET_BYTES, buildBrowserFile } from './browser-build.js';
import { VIRAMA_AT } from '../src/virama.generated.js';
import { CHECK, generator, readLf } from './gen-lib.js';

const { fail, writeOrCompare } = generator('gen-docs');
const FILES = ['README.md', 'DESIGN.md'];
const DASH = String.fromCharCode(0x2014);
// Count every opening, including malformed spellings that replacements cannot see.
export function validateDocMarkers(text, file) {
    const handled = new Set();
    const markers = /<!-- gen:(?:(?:size|bytes|budget|count):[^\s<>]+|release) -->[^\r\n]*?<!-- \/gen -->|<!-- gen:sizes:start(?: \(generated by `npm run gen`; do not edit\))? -->[\s\S]*?<!-- gen:sizes:end -->/g;
    for (const match of text.matchAll(markers)) {
        handled.add(match.index);
        if (match[0].startsWith('<!-- gen:sizes:start')) {
            handled.add(match.index + match[0].lastIndexOf('<!-- gen:sizes:end -->'));
        }
    }
    for (const match of text.matchAll(/<!--\s*gen:/g)) {
        if (!handled.has(match.index)) {
            const line = text.slice(0, match.index).split('\n').length;
            throw new Error(`${file}:${line}: unhandled gen: opening; use a supported marker and closing comment, with spaces and a single-line value.`);
        }
    }
    if (file === 'README.md') {
        if (!/^\s*rev: v\d+\.\d+\.\d+  # a release tag\s*$/m.test(text)) {
            throw new Error('README.md: missing rev: vX.Y.Z  # a release tag line.');
        }
        if (!/badgen\.net\/static\/gzip\/under%20[\d.]+%20KiB/.test(text)) {
            throw new Error('README.md: missing size badge URL.');
        }
    }
}

async function main() {
    for (const file of FILES) validateDocMarkers(readLf(file), file);

    const { version } = JSON.parse(readLf('package.json'));
    const heading = readLf('CHANGELOG.md').match(new RegExp(`^## ${version.replace(/\./g, '\\.')} ${DASH} (\\d{4}-\\d{2}-\\d{2})$`, 'm'));
    if (!heading) fail(`CHANGELOG.md has no "## ${version} ${DASH} YYYY-MM-DD" heading for the version in package.json.`);
    const release = `${version} (${heading[1]})`;

    const sizes = await measure();
    sizes.set('browser', (await buildBrowserFile()).gzipped.length);
    const budgets = new Map(PROBES.map((p) => [p.name, p.budget]));
    budgets.set('browser', GZIP_BUDGET_BYTES);

    const kib = (bytes) => `${(bytes / 1024).toFixed(1)} KiB`;
    // Budgets are round numbers: 3072 bytes reads as "3 KiB", not "3.0 KiB".
    const budgetKib = (bytes) => `${Number((bytes / 1024).toFixed(1))} KiB`;

    let viramas = 0;
    for (let cp = 0; cp <= 0x10FFFF; cp++) {
        VIRAMA_AT.lastIndex = 0;
        if (VIRAMA_AT.test(String.fromCodePoint(cp))) viramas++;
    }
    const counts = new Map([['viramas', viramas]]);

    function sizeOf(name, file) {
        if (!sizes.has(name)) fail(`${file}: unknown size probe "${name}"`);
        return /** @type {number} */ (sizes.get(name));
    }

    function budgetOf(name, file) {
        if (budgets.get(name) === undefined) fail(`${file}: size probe "${name}" has no budget`);
        return /** @type {number} */ (budgets.get(name));
    }

    // In KiB to one decimal, so the table changes only when a size really moves.
    function sizeTable() {
        const rows = [...sizes.keys()].filter((name) => name !== 'everything').map((name) => {
            const budget = budgets.get(name);
            const label = name === 'browser' ? 'prebuilt browser file' : `\`${name}\``;
            return `| ${label} | ${kib(sizeOf(name, 'table'))} | ${budget === undefined ? 'reported only' : budgetKib(budget)} |`;
        });
        return ['| Import | Gzipped | Budget |', '| --- | ---: | ---: |', ...rows].join('\n');
    }

    for (const file of FILES) {
        const current = readLf(file);
        let next = current.replace(/<!-- gen:(size|bytes):([^ ]+) -->.*?<!-- \/gen -->/g, (_, unit, name) => {
            const bytes = sizeOf(name, file);
            return `<!-- gen:${unit}:${name} -->${unit === 'size' ? kib(bytes) : bytes}<!-- /gen -->`;
        });
        next = next.replace(/<!-- gen:budget:([^ ]+) -->.*?<!-- \/gen -->/g, (_, name) =>
            `<!-- gen:budget:${name} -->${budgetKib(budgetOf(name, file))}<!-- /gen -->`);
        next = next.replace(/<!-- gen:count:([^ ]+) -->.*?<!-- \/gen -->/g, (_, name) => {
            if (!counts.has(name)) fail(`${file}: unknown count "${name}"`);
            return `<!-- gen:count:${name} -->${counts.get(name)}<!-- /gen -->`;
        });
        next = next.replace(/<!-- gen:release -->.*?<!-- \/gen -->/g, `<!-- gen:release -->${release}<!-- /gen -->`);
        next = next.replace(/<!-- gen:sizes:start[^>]*-->[\s\S]*?<!-- gen:sizes:end -->/g,
            `<!-- gen:sizes:start (generated by \`npm run gen\`; do not edit) -->\n${sizeTable()}\n<!-- gen:sizes:end -->`);
        if (file === 'README.md') {
            next = next.replace(/rev: v\d+\.\d+\.\d+(\s+# a release tag)/g, `rev: v${version}$1`);
            next = next.replace(/(badgen\.net\/static\/gzip\/under%20)[\d.]+(%20KiB)/g, `$1${budgetKib(GZIP_BUDGET_BYTES).split(' ')[0]}$2`);
        }
        const unknown = next.match(/<!-- gen:(?!size:|bytes:|budget:|count:|release -->|sizes:)[^>]*-->/);
        if (unknown) fail(`${file}: unknown marker ${unknown[0]}`);

        writeOrCompare(file, next);
    }

    if (CHECK && !process.exitCode) console.log('gen-docs: README.md and DESIGN.md are up to date.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try { await main(); } catch (error) { fail(error.message); }
}
